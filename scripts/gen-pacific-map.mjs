import { readFileSync, writeFileSync } from 'node:fs';
import { geoEquirectangular, geoPath, geoGraticule10 } from 'd3-geo';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'));
const topoLo = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8'));
const countries = feature(topo, topo.objects.countries);
const find = (id) => countries.features.find((f) => String(f.id) === String(id));
const mexico = find('484');
const japan = find('392');

const W = 1000;
const H = 520;

// Pacific-centered projection fitted around Japan (west) and Mexico (east)
const fitPoints = {
  type: 'MultiPoint',
  coordinates: [[128, 26], [148, 47], [-120, 33], [-85, 12], [-120, 9], [128, 9]],
};
const proj = geoEquirectangular().rotate([158, 0]).fitExtent([[50, 30], [W - 50, H - 30]], fitPoints);
proj.clipExtent([[0, 0], [W, H]]);
const path = geoPath(proj);
const r = (s) => s.replace(/(\d+\.\d{1})\d+/g, '$1');

const out = {
  W,
  H,
  land: r(path(feature(topoLo, topoLo.objects.land))),
  mexico: r(path(mexico)),
  japan: r(path(japan)),
  graticule: r(path(geoGraticule10())),
  mex: proj([-99.13, 19.43]).map((n) => Math.round(n * 10) / 10),
  tyo: proj([139.69, 35.68]).map((n) => Math.round(n * 10) / 10),
};

const ts = `// Auto-generated by scripts/gen-pacific-map.mjs (Natural Earth 50m via world-atlas). Do not edit by hand.
export const PACIFIC_MAP = ${JSON.stringify(out)} as const;
`;
writeFileSync('src/lib/pacificMap.ts', ts);
console.log('ok', out.mex, out.tyo, ts.length, 'bytes');

